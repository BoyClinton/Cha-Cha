int main() {
    std::string text;
    for (int i = 0; i < 40; ++i) text += "Cha-Cha menus drawn with the game's own textures. ";
    for (int k = 0; k < 3; ++k)
        for (int i = 0; i < 256; ++i) text += static_cast<char>(i);
    std::vector<uint8_t> out;
    check(inflate_zlib(kDynamic, sizeof kDynamic, out) && std::string(out.begin(), out.end()) == text, "inflate: dynamic Huffman");
    check(inflate_zlib(kFixed, sizeof kFixed, out) && std::string(out.begin(), out.end()) == "abcabcabcabc hello hello", "inflate: fixed Huffman");
    check(inflate_zlib(kStored, sizeof kStored, out) && std::string(out.begin(), out.end()) == "stored block", "inflate: stored");
    std::vector<uint8_t> bad(kDynamic, kDynamic + sizeof kDynamic);
    bad.resize(bad.size() / 2);
    check(!inflate_zlib(bad.data(), bad.size(), out), "inflate: a cut stream fails");

    // a .tex: 32x16 RGBA8, one level, texel (x, y) = (x, y, x ^ y, 255), tiled as the game stores it
    std::vector<uint8_t> linear(32 * 16 * 4);
    for (uint32_t y = 0; y < 16; ++y)
        for (uint32_t x = 0; x < 32; ++x) {
            uint8_t* p = &linear[(y * 32 + x) * 4];
            p[0] = uint8_t(x), p[1] = uint8_t(y), p[2] = uint8_t(x ^ y), p[3] = 255;
        }
    std::vector<uint8_t> tex(16 + linear.size());
    be32(tex, 0, 0x00584554);
    be32(tex, 4, (0xA5u << 20) | 2);
    be32(tex, 8, (1u << 26) | (32u << 13) | 16u);
    be32(tex, 12, (1u << 24) | (0x03u << 16) | 8u);
    mh3u::gfx::SurfaceLevel s;
    s.width = 32, s.height = 16, s.bpp = 32, s.tile_mode = 4, s.pitch = 32;
    mh3u::gfx::retile(linear.data(), tex.data() + 16, s);
    // stored in an .arc with a stored (uncompressed) zlib stream around it
    std::vector<uint8_t> z = {0x78, 0x01, 0x01, uint8_t(tex.size()), uint8_t(tex.size() >> 8), uint8_t(~tex.size()), uint8_t(~tex.size() >> 8)};
    z.insert(z.end(), tex.begin(), tex.end());
    z.insert(z.end(), {0, 0, 0, 0});  // adler32 (not checked)
    const std::string name = "GUI\\Texture\\test";
    std::vector<uint8_t> arc(12 + 0x50);
    be32(arc, 0, 0x00435241);
    arc[4] = 0, arc[5] = 16, arc[6] = 0, arc[7] = 1;
    std::memcpy(&arc[12], name.data(), name.size());
    be32(arc, 12 + 0x40, 0x241F5DEB);
    be32(arc, 12 + 0x44, uint32_t(z.size()));
    be32(arc, 12 + 0x48, uint32_t(tex.size()) << 3);
    be32(arc, 12 + 0x4C, uint32_t(arc.size()));
    arc.insert(arc.end(), z.begin(), z.end());
    std::vector<uint8_t> got, rgba;
    uint32_t w = 0, h = 0;
    check(arc_entry(arc, name, 0x241F5DEB, got) && got == tex, "arc: entry found and inflated");
    check(!arc_entry(arc, name, 0x12345678, got), "arc: another type is not that entry");
    check(tex_rgba(tex, 0, rgba, w, h) && w == 32 && h == 16 && rgba == linear, "tex: RGBA8 level 0 detiled");
    return failures ? 1 : 0;
}
