// Emits recompiled C++ for the game.
// Usage: recomp_emit <repo root> <out dir> <file count>
// Writes into <out>:
//   recomp_NN.cpp       emitted functions, exactly <file count> files (round-robin), so build systems know the outputs
//   functions.h         declarations of every function entry and every import
//   stubs.cpp           functions the emitter rejected -> ppc::unimplemented_function(addr)
//   imports.cpp         Cafe OS imports -> ppc::unimplemented_import(name) (the HLE runtime replaces these)
//   function_table.cpp  {addr, fn} for every function and {stub, fn} for every import, sorted (ppc::call_indirect)
//   emit_report.txt     accepted/rejected counts and rejection reasons
// Without the user's dump every file is written with no functions, so the build still works.
#include "emitter.h"
#include "loader.h"

#include <algorithm>
#include <cstdio>
#include <fstream>
#include <map>
#include <set>
#include <sstream>
#include <string>
#include <vector>

namespace stdfs = std::filesystem;
using namespace mh3u;

static const char* kPrelude =
    "// Generated by recomp_emit - do not edit.\n#include \"functions.h\"\n#include <bit>\n#include <cmath>\n"
    "#include <cstring>\n\nnamespace ppc = mh3u::ppc;\n\n";

static void write_if_changed(const stdfs::path& p, const std::string& text) {
    std::ifstream old(p);
    std::string prev((std::istreambuf_iterator<char>(old)), std::istreambuf_iterator<char>());
    old.close();
    if (prev != text) std::ofstream(p) << text;
}

static std::string hex8(uint32_t v) {
    char b[16];
    std::snprintf(b, sizeof b, "%08X", v);
    return b;
}

int main(int argc, char** argv) {
    if (argc < 4) {
        std::fprintf(stderr, "usage: recomp_emit <repo> <out dir> <file count>\n");
        return 2;
    }
    stdfs::path repo = argv[1], outdir = argv[2];
    const int nfiles = std::max(1, std::atoi(argv[3]));
    stdfs::create_directories(outdir);
    std::vector<std::ostringstream> files(nfiles);
    for (auto& f : files) f << kPrelude;
    std::ostringstream decls, stubs, imports, table, import_table, report;
    decls << "// Generated by recomp_emit - do not edit.\n#pragma once\n#include \"ppc_context.h\"\n\n";
    stubs << kPrelude;
    imports << kPrelude;
    table << "// Generated by recomp_emit - do not edit.\n#include \"functions.h\"\n\n"
             "extern const mh3u::ppc::FunctionEntry kFunctionTable[] = {\n";
    size_t table_count = 0;

    stdfs::path elf = repo / "extracted/0005000e10118300_v32/code/MH3G_Cafe_US.elf";
    if (stdfs::exists(elf)) {
        std::string err;
        auto img = recomp::load_image(elf, &err);
        if (!img) {
            std::fprintf(stderr, "load failed: %s\n", err.c_str());
            return 1;
        }
        struct Fn {
            uint32_t start, end;
            std::string name;
            std::vector<std::pair<uint32_t, uint32_t>> chunks;  // further body ranges [begin, end)
        };
        std::vector<Fn> fns;
        std::set<uint32_t> entries;
        // .syscall (0x02000000, just before .text) holds one 8-byte function (`nop; blr`) that crt code calls.
        if (const recomp::Section* sc = img->elf.section(".syscall"); sc && sc->size >= 8) {
            fns.push_back({sc->addr, sc->addr + sc->size, ".syscall", {}});
            entries.insert(sc->addr);
        }
        std::ifstream csv(repo / "config/functions.csv");
        std::string line;
        std::getline(csv, line);
        while (std::getline(csv, line)) {
            if (line.empty()) continue;
            uint32_t s = std::stoul(line.substr(0, 10), nullptr, 16), e = std::stoul(line.substr(11, 10), nullptr, 16);
            std::string rest = line.substr(22);
            Fn f{s, e, rest.substr(0, rest.find(",recomp")), {}};
            std::istringstream chunks(rest.substr(rest.rfind(',') + 1));
            for (std::string c; chunks >> c;)
                if (c.size() == 17 && c[8] == '-')
                    f.chunks.emplace_back(std::stoul(c.substr(0, 8), nullptr, 16), std::stoul(c.substr(9, 8), nullptr, 16));
            fns.push_back(std::move(f));
            entries.insert(s);
        }
        std::vector<std::string> import_names;
        for (const auto& im : img->imports) import_names.push_back(recomp::import_function_name(im.rpl, im.name));

        // switch tables: bctr -> table slot addresses (inline `b case` instructions), config/switches.csv
        std::map<uint32_t, std::vector<uint32_t>> switches;
        std::ifstream sw(repo / "config/switches.csv");
        std::getline(sw, line);
        while (std::getline(sw, line)) {
            std::vector<std::string> c;
            std::stringstream ss(line);
            for (std::string f; std::getline(ss, f, ',');) c.push_back(f);
            if (c.size() < 5 || c[2] != "inline" || c[4].empty()) continue;
            uint32_t bctr = std::stoul(c[0], nullptr, 16), tbl = std::stoul(c[3], nullptr, 16);
            for (int k = 0, n = std::stoi(c[4]); k < n; ++k) switches[bctr].push_back(tbl + 4u * k);
        }

        recomp::EmitEnv env;
        env.is_entry = [&](uint32_t a) { return entries.count(a) != 0; };
        env.import_call = [&](uint32_t site) -> std::string {
            auto it = img->import_calls.find(site);
            return it == img->import_calls.end() ? std::string() : import_names[it->second];
        };
        env.undefined_call = [&](uint32_t site) {
            return std::binary_search(img->undefined_refs.begin(), img->undefined_refs.end(), site);
        };
        env.switch_slots = [&](uint32_t bctr) -> const std::vector<uint32_t>* {
            auto it = switches.find(bctr);
            return it == switches.end() ? nullptr : &it->second;
        };

        // config/overrides.txt: "0xADDR name # note" - functions with hand-written replacements in src/
        std::set<uint32_t> overrides;
        {
            std::ifstream ov(repo / "config/overrides.txt");
            for (std::string l; std::getline(ov, l);)
                if (l.rfind("0x", 0) == 0) overrides.insert(static_cast<uint32_t>(std::stoul(l.substr(0, 10), nullptr, 16)));
        }

        size_t ok = 0, insns = 0, total_insns = 0;
        std::map<std::string, size_t> reasons;
        for (const Fn& f : fns) {
            decls << "PPC_FUNC(" << recomp::function_name(f.start) << ");\n";
            const bool overridden = overrides.count(f.start) != 0;
            if (overridden) decls << "PPC_FUNC(" << recomp::function_name(f.start) << "__orig);\n";
            total_insns += (f.end - f.start) / 4;
            recomp::EmitResult r;
            std::vector<recomp::CodeRange> ranges;
            auto add_range = [&](uint32_t b, uint32_t e) {
                recomp::CodeRange cr{b, {}};
                for (uint32_t a = b; a < e; a += 4) cr.words.push_back(*img->elf.read32(a));
                ranges.push_back(std::move(cr));
            };
            add_range(f.start, f.end);
            size_t fn_insns = (f.end - f.start) / 4;
            for (auto [b, e] : f.chunks) {
                add_range(b, e);
                fn_insns += (e - b) / 4;
            }
            total_insns += fn_insns - (f.end - f.start) / 4;  // chunks are part of the program too
            r = recomp::emit_function(f.start, ranges, f.name, env);
            if (r.ok && overridden) {
                // the translation becomes <name>__orig; <name> dispatches to the registered replacement
                const std::string name = recomp::function_name(f.start), head = "PPC_FUNC(" + name + ")";
                const size_t at = r.code.find(head);
                if (at != std::string::npos) r.code.replace(at, head.size(), "PPC_FUNC(" + name + "__orig)");
                r.code += head + " {\n    static ppc::GuestFunction* const slot = ppc::override_slot(0x" + hex8(f.start) +
                          "u);\n    if (*slot) (*slot)(ctx, base);\n    else " + name + "__orig(ctx, base);\n}\n";
            }
            if (r.ok) {
                files[ok % nfiles] << r.code << "\n";
                ++ok;
                insns += fn_insns;
            } else {
                ++reasons[r.reason_key];
                stubs << "// " << f.name << ": " << r.reason << "\nPPC_FUNC(" << recomp::function_name(f.start)
                      << ") { ppc::unimplemented_function(0x" << hex8(f.start) << "u); }\n";
            }
        }
        std::set<std::string> seen_imports;
        std::map<uint32_t, std::string> import_by_stub;
        for (size_t i = 0; i < img->imports.size(); ++i) {
            if (img->imports[i].data) continue;
            import_by_stub[img->imports[i].stub] = import_names[i];
            if (!seen_imports.insert(import_names[i]).second) continue;
            decls << "PPC_FUNC(" << import_names[i] << ");\n";
            // resolved once through the HLE registry (ppc::register_import); unregistered -> unimplemented_import
            std::string qualified = img->imports[i].rpl;
            if (qualified.size() > 4 && qualified.compare(qualified.size() - 4, 4, ".rpl") == 0)
                qualified.resize(qualified.size() - 4);
            qualified += "." + img->imports[i].name;
            imports << "PPC_FUNC(" << import_names[i] << ") {\n    static const ppc::GuestFunction fn = ppc::resolve_import(\""
                    << qualified << "\");\n    if (ppc::import_trace_hook) ppc::import_trace_hook(\"" << qualified
                    << "\");\n    if (!fn) ppc::unimplemented_import(\"" << qualified << "\");\n    fn(ctx, base);\n}\n";
        }
        import_table << "extern const mh3u::ppc::FunctionEntry kImportTable[] = {\n";
        for (auto& [stub, nm] : import_by_stub) import_table << "    {0x" << hex8(stub) << "u, &" << nm << "},\n";
        import_table << "};\nextern const size_t kImportCount = " << import_by_stub.size() << ";\n";
        for (const Fn& f : fns) {
            table << "    {0x" << hex8(f.start) << "u, &" << recomp::function_name(f.start) << "},\n";
            ++table_count;
        }
        char pct[32];
        std::snprintf(pct, sizeof pct, "%.1f%%", 100.0 * static_cast<double>(insns) / static_cast<double>(total_insns));
        report << "functions=" << fns.size() << " emitted=" << ok << " stubbed=" << fns.size() - ok
               << " instructions emitted=" << insns << " of " << total_insns << " (" << pct << ")"
               << " imports=" << seen_imports.size() << "\n";
        std::vector<std::pair<size_t, std::string>> top;
        for (auto& [k, v] : reasons) top.emplace_back(v, k);
        std::sort(top.rbegin(), top.rend());
        report << "rejected:\n";
        for (auto& [v, k] : top) report << "  " << v << "  " << k << "\n";
    } else {
        report << "no dump: empty output\n";
    }
    if (table_count == 0) table << "    {0u, nullptr},\n";
    table << "};\nextern const size_t kFunctionCount = " << table_count << ";\n\n";
    if (import_table.str().empty())
        import_table << "extern const mh3u::ppc::FunctionEntry kImportTable[] = {{0u, nullptr}};\n"
                        "extern const size_t kImportCount = 0;\n";
    table << import_table.str();

    for (int i = 0; i < nfiles; ++i) {
        char name[32];
        std::snprintf(name, sizeof name, "recomp_%02d.cpp", i);
        write_if_changed(outdir / name, files[i].str());
    }
    write_if_changed(outdir / "functions.h", decls.str());
    write_if_changed(outdir / "stubs.cpp", stubs.str());
    write_if_changed(outdir / "imports.cpp", imports.str());
    write_if_changed(outdir / "function_table.cpp", table.str());
    std::ofstream(outdir / "emit_report.txt") << report.str();
    std::fputs(report.str().c_str(), stdout);
    return 0;
}
