// Build step: emits the hand-encoded self-test functions (selftest_cases.h) as C++.
// Usage: emit_selftest_gen <out.cpp>
#include "emitter.h"
#include "selftest_cases.h"

#include <cstdio>
#include <fstream>
#include <set>
#include <string>

int main(int argc, char** argv) {
    if (argc < 2) return 2;
    std::ofstream out(argv[1]);
    out << "// Generated by emit_selftest_gen - do not edit.\n#include \"ppc_context.h\"\n#include <bit>\n#include <cmath>\n"
           "#include <cstring>\n\nnamespace ppc = mh3u::ppc;\n\n";
    std::set<uint32_t> entries;
    for (const auto& c : selftest::cases()) {
        entries.insert(c.addr);
        out << "PPC_FUNC(" << mh3u::recomp::function_name(c.addr) << ");\n";
    }
    out << "PPC_FUNC(" << selftest::kTestImport << ");\n\n";
    mh3u::recomp::EmitEnv env;
    env.is_entry = [&](uint32_t a) { return entries.count(a) != 0; };
    env.import_call = [](uint32_t site) {
        return site == selftest::kImportCall ? std::string(selftest::kTestImport) : std::string();
    };
    const std::vector<uint32_t> switch_slots = {selftest::kSwitch + 0x20, selftest::kSwitch + 0x24,
                                                selftest::kSwitch + 0x28};
    env.switch_slots = [&](uint32_t bctr) { return bctr == selftest::kSwitchBctr ? &switch_slots : nullptr; };
    int failed = 0;
    for (const auto& c : selftest::cases()) {
        std::vector<mh3u::recomp::CodeRange> ranges{{c.addr, c.words}};
        for (const auto& [a, w] : c.chunks) ranges.push_back({a, w});
        auto r = mh3u::recomp::emit_function(c.addr, ranges, {}, env);
        if (!r.ok) {
            std::fprintf(stderr, "emit failed for %08X: %s\n", c.addr, r.reason.c_str());
            ++failed;
            continue;
        }
        out << r.code << "\n";
    }
    // function/import tables for ppc::call_indirect (sorted by address)
    out << "extern const mh3u::ppc::FunctionEntry kFunctionTable[] = {\n";
    for (uint32_t a : entries) out << "    {" << a << "u, &" << mh3u::recomp::function_name(a) << "},\n";
    out << "};\nextern const size_t kFunctionCount = " << entries.size() << ";\n";
    out << "extern const mh3u::ppc::FunctionEntry kImportTable[] = {{0xC0000000u, &" << selftest::kTestImport
        << "}};\nextern const size_t kImportCount = 1;\n";
    return failed ? 1 : 0;
}
