# Records exactly which game build we are working on into config/target.txt.
# Every symbol address in this project is only valid for the hashes recorded here.
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent $PSScriptRoot
$outDir = Join-Path $root "extracted"
$target = Join-Path $root "config\target.txt"

$lines = @("# Generated by scripts/fingerprint.ps1 on $(Get-Date -Format s)")
foreach ($meta in Get-ChildItem $outDir -Recurse -Filter meta.xml) {
    [xml]$x = Get-Content $meta.FullName
    $lines += "title_id=$($x.menu.title_id.'#text') title_version=$($x.menu.title_version.'#text') ($($meta.Directory.Parent.Name))"
}
foreach ($f in Get-ChildItem $outDir -Recurse -Include *.rpx, *.rpl) {
    $h = (Get-FileHash $f.FullName -Algorithm SHA1).Hash.ToLower()
    $lines += "sha1=$h  $($f.FullName.Substring($root.Length + 1))"
}
$lines | Set-Content -Encoding utf8 $target
Get-Content $target
